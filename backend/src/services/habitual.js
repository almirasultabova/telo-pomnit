// Canonical shared educational questionnaire. Mirror into backend/src/services/habitual.js.
(function (root, factory) {
  const value = factory();
  if (typeof module === 'object' && module.exports) module.exports = value;
  else root.Habitual = value;
})(typeof globalThis !== 'undefined' ? globalThis : this, function () {
  'use strict';
  const version = 'habitual_reactions_v2';
  const groups = ['pause', 'accommodating', 'pushback', 'explaining'];
  const texts = [
    'Когда ко мне неожиданно обращаются, я теряю слова, хотя хочу ответить.',
    'Я соглашаюсь на просьбу, хотя уже понимаю, что не хочу её выполнять.',
    'Когда со мной не согласны, я начинаю говорить резче, чем собиралась.',
    'Когда меня спрашивают о чувствах, я начинаю объяснять причины происходящего вместо того, чтобы назвать своё чувство.',
    'В важном для меня разговоре мне бывает трудно пошевелиться, хотя я хочу двигаться.',
    'В разговоре я отказываюсь от своей позиции, хотя внутри продолжаю с ней соглашаться.',
    'Когда человек выбирает не мой вариант, я начинаю его переубеждать, ещё не выслушав до конца.',
    'Когда разговор касается моих чувств, я незаметно для себя перехожу к обсуждению фактов.',
    'Во время важного для меня разговора я внезапно замолкаю, хотя хочу продолжить свою мысль.',
    'Прежде чем назвать своё желание, я пытаюсь угадать, какой ответ устроит другого человека.',
    'На замечание я отвечаю раздражённо раньше, чем успеваю решить, как хочу ответить.',
    'В разговоре о собственных переживаниях я перехожу к общим рассуждениям вместо описания того, что чувствую сама.',
    'Когда происходит что-то неожиданное, я на какое-то время замечаю пустоту в мыслях.',
    'Я меняю уже высказанный отказ на согласие, заметив недовольство собеседника.',
    'На чужое предложение я сначала возражаю, ещё не разобравшись, что именно предлагают.',
    'Рассказывая о собственном переживании, я говорю о нём так, будто оно относится к другому человеку.'
  ];
  const items = texts.map((text, i) => ({ id: String(i + 1).padStart(2, '0'), text, group: groups[i % 4] }));
  const choices = ['Никогда или почти никогда', 'Редко', 'Иногда', 'Часто', 'Почти всегда', 'Трудно ответить', 'Не было таких ситуаций'];
  const descriptions = {
    pause: { name: 'Замирание', title: 'В ваших ответах чаще встречалось замирание.', text: 'Вы чаще отмечали остановку речи, движения или мысли в ситуациях, которые для вас значимы. По опросу нельзя определить причину этой реакции. Посмотрите, насколько описание совпадает с вашим опытом.', observe: 'Замечайте разницу между остановкой, которая возникает сама, и паузой, которую вы выбираете, чтобы подумать.' },
    accommodating: { name: 'Подстраивание', title: 'В ваших ответах чаще встречалось подстраивание.', text: 'Вы чаще отмечали согласие или уступку, хотя ваше собственное желание или позиция оставались другими. Это отличается от согласия, которое вы выбираете свободно.', observe: 'Замечайте, успеваете ли вы услышать своё желание до ответа другому человеку.' },
    pushback: { name: 'Защитный отпор', title: 'В ваших ответах чаще встречался защитный отпор.', text: 'Вы чаще отмечали резкий ответ или возражение до того, как успеваете выбрать ответ или выслушать другого человека. Спокойное обозначение границ само по себе сюда не относится.', observe: 'Замечайте разницу между выбранным «нет» и возражением, которое возникает раньше вашего решения.' },
    explaining: { name: 'Уход в объяснения', title: 'В ваших ответах чаще встречался уход в объяснения.', text: 'Вы чаще отмечали переход к фактам и рассуждениям вместо рассказа о собственном переживании. По этим ответам нельзя определить, почему так происходит.', observe: 'Замечайте, остаётся ли доступно ваше собственное чувство, пока вы объясняете событие.' }
  };
  function calculate(answers) {
    if (!Array.isArray(answers) || answers.length !== 16 || answers.some(x => !(Number.isInteger(x) && x >= 0 && x <= 6))) throw new Error('INVALID_HABITUAL_ANSWERS');
    const sums = groups.map((_, k) => answers.reduce((s, v, i) => s + (i % 4 === k && v <= 4 ? v : 0), 0));
    const scores = Object.fromEntries(groups.map((g, i) => [g, sums[i]]));
    const result = { version, answers: answers.slice(), scores, state: '', leadingGroup: null, tiedGroups: [] };
    if (answers.some(x => x > 4)) result.state = 'incomplete';
    else if (answers.every(x => x === 0)) result.state = 'not_identified';
    else if (answers.every(x => x <= 1)) result.state = 'low_frequency';
    else {
      const max = Math.max(...sums), winners = sums.map((s, i) => s === max ? i : -1).filter(i => i >= 0);
      if (winners.length > 1) { result.state = 'tie'; result.tiedGroups = winners.map(i => groups[i]); }
      else {
        const w = winners[0]; let stable = true;
        for (let omit = 0; omit < 16; omit++) {
          const means = sums.map((s, k) => (s - (omit % 4 === k ? answers[omit] : 0)) / (omit % 4 === k ? 3 : 4));
          if (means.some((s, k) => k !== w && s >= means[w])) { stable = false; break; }
        }
        result.state = stable ? 'leading_in_answers' : 'close';
        if (stable) result.leadingGroup = groups[w];
      }
    }
    return result;
  }
  function message(result) {
    if (result.leadingGroup && descriptions[result.leadingGroup]) return descriptions[result.leadingGroup];
    const messages = {
      incomplete: ['Пока недостаточно ответов для сравнения реакций', 'Можно вернуться к пропущенным утверждениям. Если оценить их трудно, оставьте как есть — ваши выбранные ответы остаются доступными.'],
      not_identified: ['Среди предложенных реакций ведущая не выделилась', 'Вы почти не отмечали перечисленные проявления. Этот набор может не описывать ваш опыт.'],
      low_frequency: ['Вы редко отмечали предложенные реакции', 'По этим ответам не будем называть одну из них ведущей. Можно посмотреть свои ответы и наблюдать, насколько эти описания вам знакомы.'],
      tie: ['В ответах одинаково часто встречались несколько реакций', 'Одну ведущую реакцию по этим ответам выделить не удалось.'],
      close: ['По ответам нельзя выделить одну ведущую реакцию', 'Несколько реакций оказались близки по ответам. Сейчас полезнее посмотреть на отмеченные проявления без одного итогового названия.']
    };
    const pair = messages[result.state] || messages.incomplete;
    return { title: pair[0], text: pair[1] };
  }
  return { version, groups, items, choices, descriptions, calculate, message };
});
